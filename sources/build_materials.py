def wrap(t,n=35):
    # 中文近似全宽，拉丁字符按半宽计；折行不截字
    rows=[];row='';w=0
    for ch in t:
        cw=1 if ord(ch)>255 else .55
        if w+cw>n:rows.append(row);row='';w=0
        row+=ch;w+=cw
    if row:rows.append(row)
    return rows
